#!/bin/sh
# Builds the HACS bundle (russtum-cards.js) from src/.
# src/ is the source of truth — never edit russtum-cards.js by hand.
#
#   ./build.sh          rebuild the bundle
#   ./build.sh --check  exit 1 if the bundle is out of date (used by CI)
set -eu
cd "$(dirname "$0")"

OUT=russtum-cards.js
# Load order: the shared editor kit first, then the cards.
KIT=src/editor-kit.js
CARDS="nas ups media-server minecraft docker device-monitor sonarr-upcoming download-queue"

build() {
  echo "// Russtum Cards bundle — GENERATED by build.sh from src/. Do not edit by hand."
  echo
  echo "// ═══ $KIT ═══"
  cat "$KIT"
  for c in $CARDS; do
    f="src/$c-card.js"
    [ -f "$f" ] || { echo "build.sh: missing $f" >&2; exit 1; }
    echo
    echo "// ═══ $f ═══"
    # Each card gets its own scope so top-level helpers can't collide.
    echo "(() => {"
    cat "$f"
    echo "})();"
  done
  echo
  echo "console.info('%c RUSSTUM-CARDS %c NAS · UPS · Media · Minecraft · Docker · Device Monitor · Sonarr Upcoming · Download Queue ', 'color:#fff;background:#1976d2;font-weight:700;padding:2px 6px;border-radius:3px 0 0 3px', 'color:#1976d2;background:rgba(25,118,210,0.1);font-weight:600;padding:2px 6px;border-radius:0 3px 3px 0');"
}

if [ "${1:-}" = "--check" ]; then
  if build | cmp -s - "$OUT"; then
    echo "$OUT is up to date."
  else
    echo "$OUT is out of date — run ./build.sh and commit the result." >&2
    exit 1
  fi
else
  build > "$OUT"
  echo "Wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)."
fi
